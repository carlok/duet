"""Lean 4 certificates for finite countermodels (T7), in the layout of the user's curve-symmetry-lean project.

    python -m soup.lean_cert model --json /data/check/s10_model.json --name S10 --out /lean
    then: podman run --rm -v "$PWD/lean:/src" -v "<reuse project>:/reuse:ro" soup-lean sh /src/check.sh

For a theory T (two binary operations f = ·, g = ∘), a model (Fin n, F, G) and claims e that fail in it, the module
lean/Duet/<Name>.lean states
    def Theory {α : Type} (f g : α → α → α) : Prop      -- the conjunction of T's laws, each universally closed
    theorem model : Theory F G                             -- by decide
    theorem not_<k> : ¬ ∀ (α : Type) (f g : α → α → α), Theory f g → <claim k>
so each non-implication T ⊭ e is a Lean theorem about all types, proved by exhibiting the tables. Only `decide`
is used (no native_decide), and verification/Audit.lean allows the axioms propext, Classical.choice, Quot.sound.
"""
import argparse
import json
import re
from pathlib import Path

VARS = 'xyzwuv'


def lean_term(t, f='f', g='g'):
    if t[0] == 'v': return VARS[t[1]]
    return f"({f if t[0] == 'f' else g} {lean_term(t[1], f, g)} {lean_term(t[2], f, g)})"


def _vars(t): return {t[1]} if t[0] == 'v' else _vars(t[1]) | _vars(t[2])


def lean_law(L, R, ty='α', f='f', g='g'):
    vs = sorted(_vars(L) | _vars(R))
    body = f"{lean_term(L, f, g)} = {lean_term(R, f, g)}"
    return f"(∀ {' '.join(VARS[v] for v in vs)} : {ty}, {body})" if vs else f"({body})"


def table(T):
    return '![' + ', '.join('![' + ', '.join(str(v) for v in row) + ']' for row in T) + ']'


def module(name, laws, claims, n, F, G, source):
    """laws, claims: lists of (text, (L, R)) with trees; returns the Lean source."""
    ax = '\n  ∧ '.join(lean_law(L, R) for _, (L, R) in laws)
    out = [f'import Mathlib.Data.Fintype.Basic', 'import Mathlib.Data.Fin.VecNotation', '',
           f'/-! # {name}: a {n}-element countermodel', '',
           'Generated by `soup.lean_cert` from tables that `soup.check_offline.check_finite` accepted.',
           f'Source: `{source}`.', '',
           'Laws of the theory (· = `f`, ∘ = `g`):', *[f'- `{s}`' for s, _ in laws], '',
           'Claims refuted:', *[f'- `{s}`' for s, _ in claims], '-/', '',
           f'namespace Duet.{name}', '',
           f'/-- The theory {name}: the conjunction of its laws. -/',
           f'def Theory {{α : Type}} (f g : α → α → α) : Prop :=\n  {ax}', '',
           f'/-- The operation `·` of the countermodel. -/',
           f'def F : Fin {n} → Fin {n} → Fin {n} := {table(F)}', '',
           f'/-- The operation `∘` of the countermodel. -/',
           f'def G : Fin {n} → Fin {n} → Fin {n} := {table(G)}', '',
           '/-- The tables satisfy every law of the theory. -/',
           'theorem model : Theory F G := by',
           '  unfold Theory', '  decide', '']
    for k, (s, (L, R)) in enumerate(claims):
        out += [f'/-- The theory does not imply `{s}`. -/',
                f'theorem not_{k} : ¬ ∀ (α : Type) (f g : α → α → α), Theory f g → {lean_law(L, R)} := by',
                '  intro h', f'  have := h (Fin {n}) F G model', '  revert this', '  decide', '']
    out += [f'end Duet.{name}', '']
    return '\n'.join(out)


AUDIT = '''import Duet
import Lean.Util.CollectAxioms

/-! Dependency audit, as in curve-symmetry-lean: every declaration in the namespace `Duet` may use only the
axioms propext, Classical.choice and Quot.sound (no native_decide, no sorry). -/

open Lean in
run_cmd do
  let allowed : Array Name := #[`propext, `Classical.choice, `Quot.sound]
  let env ← getEnv
  let mut checked : Nat := 0
  for (name, _) in env.constants.toList do
    if (`Duet).isPrefixOf (privateToUserName name) then
      let axioms ← collectAxioms name
      for axiomName in axioms do
        unless allowed.contains axiomName do
          throwError "Forbidden axiom {axiomName} in {name}"
      checked := checked + 1
  if checked == 0 then
    throwError "Empty audit: the certificates were not loaded"
  logInfo m!"Axiom audit passed: {checked} declarations; allowlist propext, Classical.choice, Quot.sound"
'''

CHECK = '''#!/bin/sh
# Check every certificate with Lean, reusing the compiled packages of an existing Lake project mounted read-only
# at /reuse (Lean v4.35.0, Mathlib v4.35.0). No Lake, no downloads (pattern of curve-symmetry-lean/lean/check.sh).
set -eu
src=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
reuse=${REUSE:-/reuse}
[ -f "$reuse/.lake/packages/mathlib/.lake/build/lib/lean/Mathlib.olean" ] || { echo "no compiled Mathlib at $reuse" >&2; exit 2; }
paths=
for p in "$reuse"/.lake/packages/*; do
  [ -d "$p/.lake/build/lib/lean" ] && paths="${paths:+$paths:}$p/.lake/build/lib/lean"
done
build=$(mktemp -d)
mkdir -p "$build/Duet"
export LEAN_PATH="$build:$paths"
cd "$src"
for m in $(awk '/^import Duet\\./ {print $2}' Duet.lean); do
  f=$(echo "$m" | tr . /).lean
  lean -DwarningAsError=true -o "$build/$(echo "$m" | tr . /).olean" "$f"
  echo "checked $m"
done
lean -DwarningAsError=true -o "$build/Duet.olean" Duet.lean
lean -DwarningAsError=true verification/Audit.lean
'''


def write_project(out, name, src):
    out = Path(out); (out / 'Duet').mkdir(parents=True, exist_ok=True); (out / 'verification').mkdir(exist_ok=True)
    (out / 'Duet' / f'{name}.lean').write_text(src)
    mods = sorted(p.stem for p in (out / 'Duet').glob('*.lean'))
    (out / 'Duet.lean').write_text(''.join(f'import Duet.{m}\n' for m in mods))
    (out / 'verification' / 'Audit.lean').write_text(AUDIT)
    (out / 'check.sh').write_text(CHECK)
    return mods


def main():
    from .data import TREES, LAWS
    from .named import law_index
    ap = argparse.ArgumentParser()
    ap.add_argument('kind', choices=['model']); ap.add_argument('--json', required=True)
    ap.add_argument('--name', required=True); ap.add_argument('--out', default='/lean')
    a = ap.parse_args()
    if not re.fullmatch(r'[A-Z][A-Za-z0-9]*', a.name): raise SystemExit('name must be a Lean identifier')
    r = json.load(open(a.json))
    T = [law_index(s.replace(' ', '')) for s in r['laws']]
    laws = [(LAWS[t], TREES[t]) for t in T]
    refuted = [s for s, c in r['claims'].items() if c.get('refuted')]
    claims = [(s, TREES[law_index(s.replace(' ', ''))]) for s in refuted]
    src = module(a.name, laws, claims, r['n'], r['F'], r['G'], r.get('source', a.json).replace('/data/', 'work/'))
    mods = write_project(a.out, a.name, src)
    print(f'wrote Duet/{a.name}.lean ({len(claims)} non-implications); modules: {mods}')


if __name__ == '__main__':
    main()
